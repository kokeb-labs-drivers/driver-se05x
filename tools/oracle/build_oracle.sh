#!/usr/bin/env bash
# Regenerates tests/vectors/nxp_oracle_vectors.hpp from a vendor middleware checkout used as a test
# oracle only. The checkout stays outside the repository; this script compiles two of its files with
# tools/oracle/oracle_capture.c in a temporary directory, runs the result and writes the header.
#
#   tools/oracle/build_oracle.sh <plug-and-trust checkout> <output header>
#
# Use a copy of the checkout in a scratch directory. The capture binary runs under the command in
# ORACLE_RUNNER when it is set, for example a sandbox that denies network access on macOS:
#   ORACLE_RUNNER="sandbox-exec -p '(version 1)(allow default)(deny network*)'"
# The harness reads no file of the checkout at run time; it only calls the command builders.
#
# The checkout's commit is recorded in tests/vectors/THIRD_PARTY.md; check it before regenerating.
# Copyright (c) 2026 The driver-se05x authors. SPDX-License-Identifier: MIT
set -euo pipefail

mw="$1"
out="$2"
here="$(cd "$(dirname "$0")" && pwd)"
work="$(mktemp -d "${TMPDIR:-/tmp}/oracle.XXXXXX")"
trap 'rm -rf "$work"' EXIT

gen() { # gen <namespace> <sed expression for the feature file>
  local ns="$1" expr="$2" cfg="$work/$1"
  mkdir -p "$cfg"
  sed -e "$expr" "$mw/fsl_sss_ftr.h" >"$cfg/fsl_sss_ftr.h"
  local inc=(-I"$cfg" -I"$mw/hostlib/hostLib/inc" -I"$mw/hostlib/hostLib/libCommon/infra"
    -I"$mw/hostlib/hostLib/libCommon/log" -I"$mw/hostlib/hostLib/libCommon/smCom"
    -I"$mw/hostlib/hostLib/platform/inc" -I"$mw/hostlib/hostLib/se05x_03_xx_xx" -I"$mw/sss/inc"
    -I"$mw/sss/port/default" -I"$mw/sss/ex/inc")
  cc -std=c99 -w -DSSS_USE_FTR_FILE "${inc[@]}" -o "$cfg/capture" "$here/oracle_capture.c" \
    "$mw/hostlib/hostLib/se05x_03_xx_xx/se05x_APDU.c" "$mw/hostlib/hostLib/se05x/src/se05x_tlv.c"
  {
    echo "namespace $ns {"
    if [ -n "${ORACLE_RUNNER:-}" ]; then
      eval "$ORACLE_RUNNER" '"$cfg/capture"'
    else
      "$cfg/capture"
    fi
    echo "} // namespace $ns"
  } >>"$work/body"
}

: >"$work/body"
# Applet 7.2 (the checkout's default) and applet 3.x.
gen v7 's/^#define SSS_HAVE_SE05X_VER_07_02 .*/#define SSS_HAVE_SE05X_VER_07_02 1/'
gen v3 's/^#define SSS_HAVE_SE05X_VER_07_02 .*/#define SSS_HAVE_SE05X_VER_07_02 0/;s/^#define SSS_HAVE_SE05X_VER_03_XX .*/#define SSS_HAVE_SE05X_VER_03_XX 1/'

{
  echo "/**"
  echo " * @file nxp_oracle_vectors.hpp"
  echo " * @brief C-APDU headers and TLV bodies recorded from the vendor middleware (an oracle, see"
  echo " * THIRD_PARTY.md), for applet 7.2 (namespace v7) and 3.x (namespace v3). Generated by"
  echo " * tools/oracle/build_oracle.sh; do not edit."
  echo " * @copyright Copyright (c) 2026 The driver-se05x authors. SPDX-License-Identifier: MIT"
  echo " */"
  echo "#ifndef SE05X_TEST_NXP_ORACLE_VECTORS_HPP"
  echo "#define SE05X_TEST_NXP_ORACLE_VECTORS_HPP"
  echo ""
  echo "#include <array>"
  echo "#include <cstdint>"
  echo "#include <span>"
  echo ""
  echo "namespace oracle {"
  echo ""
  echo "/// One recorded command: the four header bytes, the TLV body and whether an Le was asked for."
  echo "struct Apdu {"
  echo "  std::array<uint8_t, 4> header;"
  echo "  std::span<const uint8_t> body;"
  echo "  bool has_le;"
  echo "};"
  echo ""
  cat "$work/body"
  echo ""
  echo "} // namespace oracle"
  echo ""
  echo "#endif // SE05X_TEST_NXP_ORACLE_VECTORS_HPP"
} >"$out"
